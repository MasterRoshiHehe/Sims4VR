#!/usr/bin/env python3
"""Packs AMD's FidelityFX FSR 1 shader headers (src/ffx, MIT) into src/fsr_ffx.inc for
src/fsr.cpp, which compiles them at run time. Comments and blank lines are dropped to keep
the DLL small; the licence text stays in front. Rerun after replacing the headers."""
import os, re, sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
src = os.path.join(root, 'src', 'ffx')

def strip(text):
    out = []
    for line in text.splitlines():
        line = re.sub(r'//.*', '', line).rstrip()
        if line: out.append(line)
    return '\n'.join(out) + '\n'

licence = open(os.path.join(src, 'LICENSE.txt'), encoding='utf-8').read().strip()
parts = ['// Generated by tools/gen_fsr_shader.py from src/ffx (AMD FidelityFX FSR 1). Do not edit.\n']
parts.append('static const char kFfxLicence[] = R"FFX(' + licence + '\n)FFX";\n')
for name, var in (('ffx_a.h', 'kFfxA'), ('ffx_fsr1.h', 'kFfxFsr1')):
    body = strip(open(os.path.join(src, name), encoding='utf-8').read())
    if ')FFX"' in body: sys.exit('delimiter clash in ' + name)
    parts.append('static const char %s[] = R"FFX(\n%s)FFX";\n' % (var, body))
open(os.path.join(root, 'src', 'fsr_ffx.inc'), 'w', encoding='utf-8', newline='\n').write(''.join(parts))
print('src/fsr_ffx.inc written')
