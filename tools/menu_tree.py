#!/usr/bin/env python3
"""Dumps the debug menu tree from src/settings.cpp: python3 tools/menu_tree.py [--md]  (--md writes docs/MENU-PATHS.md)."""
import re, sys, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
s = open(os.path.join(root, 'src/settings.cpp'), encoding='utf-8').read()
pages = re.findall(r'^    \{L"([^"]*)", L"((?:[^"\\]|\\.)*)", (?:L"([^"]*)"|nullptr)', s, re.M)
alias = dict(re.findall(r'const wchar_t\* (\w+) = L"([^"]*)";', s))
a = s.index('std::vector<Row> rows = {'); b = s.index("// Each HUD element's own page")
body = s[a:b]
rows, links = {}, {}
call = re.compile(r'^        (?:toggle|number|flag|choice|component|angle|scriptNumber|percent|foley|link)\((L"[^"]*"|\w+), L"((?:[^"\\]|\\.)*)"', re.M)
for m in re.finditer(r'^        (toggle|number|flag|choice|component|angle|scriptNumber|percent|foley|link)\((L"[^"]*"|\w+), (L"(?:[^"\\]|\\.)*")', body, re.M):
    k, g, lab = m.group(1), m.group(2), m.group(3)[2:-1].replace('\\"', '"')
    g = g[2:-1] if g.startswith('L"') else alias.get(g, g)
    if k == 'link':
        tm = re.search(r'link\([^,]+, L"(?:[^"\\]|\\.)*", (L"[^"]*"|\w+)\)', body[m.start():m.start() + 500])
        t = tm.group(1); t = t[2:-1] if t.startswith('L"') else alias.get(t, t)
        links.setdefault(g, []).append((lab, t))
    else:
        rows.setdefault(g, []).append(lab)
name = {p[0]: p[1] for p in pages}
out = []
def walk(g, d, seen):
    n = len(rows.get(g, [])) + len(links.get(g, []))
    out.append('  ' * d + f'[{name.get(g, g)}] ({n} rows)')
    for lab in rows.get(g, []): out.append('  ' * (d + 1) + '- ' + lab)
    for lab, t in links.get(g, []):
        out.append('  ' * (d + 1) + f'> {lab}')
        if t not in seen: walk(t, d + 2, seen | {t})
for g in ('Play', 'Settings', 'Testing'):
    walk(g, 0, {g})
walk('Options', 0, {'Options'})
if '--md' in sys.argv:
    hdr = open(os.path.join(root, 'docs/MENU-PATHS.header.md'), encoding='utf-8').read()
    md = [hdr, '', '## Tree (page [rows]; > opens a sub page; generated by tools/menu_tree.py --md)', '', '```']
    md += out + ['```', '', 'Wrist HUD pieces (Watch, Needs, Moodlets, Action queue, Build button, Wants, Pause symbol, Clock while asleep) are generated: each holds its on switch where it has one, Position x3, Turn x3, around-the-arm (arms only) and Size; the open page shows the green placement box. Lot name and traits on arrival is a sub page of Wrist HUD.',
           '', 'Other mods (Integrated Body Physics, Extended Sound Control, Claude Performance, Claude Bustin Out) have their own pages under the front page "Other mods".']
    open(os.path.join(root, 'docs/MENU-PATHS.md'), 'w', encoding='utf-8').write('\n'.join(md) + '\n')
else:
    print('\n'.join(out))
